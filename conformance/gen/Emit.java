// Emit — writes the cases.
//
// For a batch of stitchings it writes a pair:
//
//   Case<N>.java       a class whose main prints ONE LINE per stitching, in order
//   Case<N>.expected   the composed expected stdout, one line per stitching, same order
//
// Each stitching gets its own private static method. That is not cosmetic: it gives every
// stitching a private scope, so a void snippet that declares a local can never collide with
// another's, and it keeps main a flat call list rather than one enormous method body.
//
// A stitching whose Val is THROWS is wrapped in try/catch and prints the caught exception's
// class name; its expected line is that name (Class.getName() is §20.3.2 fully qualified,
// so "java.lang.ArithmeticException", not "ArithmeticException").
//
// ENCODING. The .expected file is a byte-for-byte model of stdout, so it is written the way
// PrintStream writes: each char as its LOW 8 BITS (java.io.PrintStream.writeString --
// "Each char is written as its low 8 bits (JLS 1.0 22.14 -- byte streams, no charset)").
// UTF-8 here would silently disagree with the program for any char above 0x7F.
//
// The .java file, by contrast, is gated to pure ASCII. A snippet that needs a non-ASCII
// character must render it as a \\uXXXX escape (JLS 3.3, which javelinac handles in-grammar).
// A generated case that fails to compile is a bug, never an expectation, so the gate fires
// at generation time rather than leaving it for the compiler to trip over.
public class Emit {

    private final String dir;
    private final int    perCase;

    private int caseCount = 0;
    private int lineCount = 0;
    private final java.util.Vector names    = new java.util.Vector();  // "Case0", ...
    private final java.util.Vector sections = new java.util.Vector();  // union, unsorted

    /** @param dir     output directory; created if absent
     *  @param perCase stitchings per Case file. Must be > 0. */
    public Emit(String dir, int perCase) {
        if (dir == null || dir.length() == 0) throw new RuntimeException("Emit: no output directory");
        if (perCase <= 0) throw new RuntimeException("Emit: perCase must be positive, got " + perCase);
        this.dir = dir;
        this.perCase = perCase;
    }

    /** Write every stitching, batched `perCase` to a file. Returns the number of Case files
     *  written. Call once; batches continue numbering across calls if called again. */
    public int write(Stitching[] all) throws java.io.IOException {
        java.io.File d = new java.io.File(dir);
        if (!d.exists()) d.mkdirs();
        if (!d.isDirectory()) throw new java.io.IOException("not a directory: " + dir);

        int written = 0;
        int i = 0;
        while (i < all.length) {
            int n = all.length - i;
            if (n > perCase) n = perCase;
            Stitching[] batch = new Stitching[n];
            for (int j = 0; j < n; j++) batch[j] = all[i + j];
            writeCase(caseCount, batch);
            caseCount++;
            written++;
            i += n;
        }
        return written;
    }

    private void writeCase(int n, Stitching[] batch) throws java.io.IOException {
        String cls = "Case" + n;

        // --- the union of the batch's sections, dotted-numerically sorted ---------------
        java.util.Vector secs = new java.util.Vector();
        for (int i = 0; i < batch.length; i++) {
            String[] s = batch[i].sections();
            for (int j = 0; j < s.length; j++) {
                if (!secs.contains(s[j])) secs.addElement(s[j]);
                if (!sections.contains(s[j])) sections.addElement(s[j]);
            }
        }
        String[] sorted = sortSections(secs);

        // --- the source ----------------------------------------------------------------
        StringBuffer src = new StringBuffer();
        src.append("// GENERATED by conformance/gen -- DO NOT EDIT.\n");
        src.append("// Every line this prints is composed, never observed: see ").append(cls).append(".expected.\n");
        src.append("// A case that fails to compile is a bug in the generator or in javelinac.\n");
        src.append("// stitchings: ").append(batch.length).append("\n");
        src.append("//\n");
        for (int i = 0; i < sorted.length; i++) src.append("// JLS ").append(sorted[i]).append("\n");
        src.append("\n");

        // --- single-type imports, ahead of every declaration (§7.5) --------------------
        java.util.Vector imps = new java.util.Vector();
        for (int i = 0; i < batch.length; i++) batch[i].collectImports(imps);
        if (imps.size() > 0) {
            for (int i = 0; i < imps.size(); i++)
                src.append("import ").append((String) imps.elementAt(i)).append(";\n");
            src.append("\n");
        }

        // --- companion type declarations, hoisted to file scope ------------------------
        // Some sections cannot be reached from an expression: §4.5.3's class variable,
        // instance variable and constructor parameter are declarations, not statements. A
        // snippet that needs one implements Declaring and its text is emitted here, ahead of
        // the case class, deduplicated across the whole batch — a case is one compilation
        // unit, so two snippets naming the same helper must not declare it twice.
        java.util.Vector decls = new java.util.Vector();
        for (int i = 0; i < batch.length; i++) batch[i].collectDecls(decls);
        for (int i = 0; i < decls.size(); i++)
            src.append((String) decls.elementAt(i)).append("\n\n");

        src.append("public class ").append(cls).append(" {\n\n");

        src.append("    public static void main(String[] args) {\n");
        for (int i = 0; i < batch.length; i++) src.append("        s").append(i).append("();\n");
        src.append("    }\n");

        StringBuffer exp = new StringBuffer();
        for (int i = 0; i < batch.length; i++) {
            Stitching st = batch[i];
            Val       v  = st.expect();
            boolean   isVoid = st.type().equals("void");

            src.append("\n    // ").append(i).append("  ").append(comment(st.id())).append("\n");
            src.append("    private static void s").append(i).append("() {\n");
            if (v.isThrows()) {
                src.append("        try {\n");
                src.append(isVoid ? "            " : "            System.out.println(");
                src.append(st.render());
                src.append(isVoid ? "\n" : ");\n");
                src.append("        } catch (Throwable __t) {\n");
                src.append("            System.out.println(__t.getClass().getName());\n");
                src.append("        }\n");
            } else if (isVoid) {
                src.append("        ").append(st.render()).append("\n");
            } else {
                src.append("        System.out.println(").append(st.render()).append(");\n");
            }
            src.append("    }\n");

            exp.append(v.display()).append("\n");
            lineCount++;
        }
        src.append("}\n");

        String source = src.toString();
        requireAscii(cls + ".java", source);

        writeFile(cls + ".java", source);
        writeFile(cls + ".expected", exp.toString());
        names.addElement(cls);
    }

    // ---- results -----------------------------------------------------------------------

    public int cases() { return caseCount; }

    /** Total expected lines written, across every case. */
    public int lines() { return lineCount; }

    public String[] caseNames() {
        String[] out = new String[names.size()];
        for (int i = 0; i < out.length; i++) out[i] = (String) names.elementAt(i);
        return out;
    }

    /** Every JLS section any written stitching exercises, dotted-numerically sorted. */
    public String[] sectionsCovered() { return sortSections(sections); }

    // ---- file I/O ----------------------------------------------------------------------

    private void writeFile(String name, String content) throws java.io.IOException {
        writeText(dir, name, content);
    }

    /** Write `text` to dir/name, one char per byte. Shared with GenMain, which writes the
     *  cap-drop record into the same directory as the cases it qualifies. */
    public static void writeText(String dir, String name, String text) throws java.io.IOException {
        String path = (dir == null || dir.length() == 0 || dir.equals(".")) ? name : (dir + "/" + name);
        byte[] data = lowBytes(text);
        java.io.FileOutputStream f = new java.io.FileOutputStream(path);
        f.write(data, 0, data.length);
        f.close();
    }

    /** Each char as its low 8 bits -- exactly what PrintStream.writeString emits, so the
     *  .expected file is a byte-for-byte model of the program's stdout. */
    // The narrowing is the point, not an accident: §5.1.3 keeps the low 8 bits, which is
    // precisely the byte PrintStream writes. javelinac warns on it because the value can
    // exceed a signed byte's range; that is the intended wrap.
    private static byte[] lowBytes(String s) {
        byte[] b = new byte[s.length()];
        for (int i = 0; i < b.length; i++) b[i] = (byte) (s.charAt(i) & 0xFF);
        return b;
    }

    private static void requireAscii(String what, String s) {
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c > 127 || c == 0)
                throw new RuntimeException(what + ": generated source holds a non-ASCII char (\\u"
                    + hex4(c) + ") at offset " + i
                    + " -- render it as a \\uXXXX escape (JLS 3.3)");
        }
    }

    private static String hex4(char c) {
        String h = Integer.toHexString(c);
        while (h.length() < 4) h = "0" + h;
        return h;
    }

    /** A stitching id is dotted and parenthesised, but it lands in a // comment, so anything
     *  that would end the line is folded to a space. */
    private static String comment(String s) {
        StringBuffer b = new StringBuffer(s.length());
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            b.append((c == '\n' || c == '\r') ? ' ' : c);
        }
        return b.toString();
    }

    // ---- section ordering ---------------------------------------------------------------
    //
    // Dotted-numeric, so 15.9 precedes 15.10 (lexicographic would not) and a section with
    // more components sorts after its prefix. Insertion sort: the input is a few dozen
    // strings, and it is stable and obvious.

    static String[] sortSections(java.util.Vector v) {
        String[] a = new String[v.size()];
        for (int i = 0; i < a.length; i++) a[i] = (String) v.elementAt(i);
        for (int i = 1; i < a.length; i++) {
            String x = a[i];
            int j = i - 1;
            while (j >= 0 && cmpSection(a[j], x) > 0) { a[j + 1] = a[j]; j--; }
            a[j + 1] = x;
        }
        return a;
    }

    static int cmpSection(String a, String b) {
        String[] pa = split(a), pb = split(b);
        int n = pa.length < pb.length ? pa.length : pb.length;
        for (int i = 0; i < n; i++) {
            int na = asInt(pa[i]), nb = asInt(pb[i]);
            if (na >= 0 && nb >= 0) { if (na != nb) return na < nb ? -1 : 1; }
            else { int c = pa[i].compareTo(pb[i]); if (c != 0) return c; }
        }
        if (pa.length == pb.length) return 0;
        return pa.length < pb.length ? -1 : 1;
    }

    private static String[] split(String s) {
        int parts = 1;
        for (int i = 0; i < s.length(); i++) if (s.charAt(i) == '.') parts++;
        String[] out = new String[parts];
        int start = 0;
        for (int k = 0; k < parts; k++) {
            int dot = (k == parts - 1) ? -1 : s.indexOf('.', start);
            if (dot < 0) { out[k] = s.substring(start); start = s.length(); }
            else         { out[k] = s.substring(start, dot); start = dot + 1; }
        }
        return out;
    }

    /** The component as a non-negative int, or -1 if it is not all digits. */
    private static int asInt(String s) {
        if (s.length() == 0) return -1;
        int v = 0;
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c < '0' || c > '9') return -1;
            v = v * 10 + (c - '0');
        }
        return v;
    }
}
